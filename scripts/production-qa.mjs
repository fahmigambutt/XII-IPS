import { chromium } from '@playwright/test';
import { createApp } from '../server/app.js';
import { createAdmin } from '../server/database.js';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { randomBytes } from 'node:crypto';
import assert from 'node:assert/strict';
const dataDir=await mkdtemp(join(tmpdir(),'yearbook-production-'));
const app=createApp({dataDir,production:true});
const password=randomBytes(20).toString('hex');
await createAdmin(app.locals.db,'production-qa',password);
const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
const url=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({channel:'chrome',headless:true});
const results=[],errors=[];
const pass=name=>{results.push({name,status:'PASS'});console.log(`PASS ${name}`);};
try{
  const page=await browser.newPage({viewport:{width:1440,height:960}});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',message=>{if(/Refused to|Content Security Policy/i.test(message.text()))errors.push(message.text());});
  const response=await page.goto(url);
  assert.ok(response.headers()['content-security-policy']);
  await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  await page.locator('#loading').waitFor({state:'hidden'});
  await page.screenshot({path:'docs/qa/production-cover.png'});
  await page.evaluate(()=>window.__YEARBOOK__.open());
  for(const next of [4,6,8,10,12]){await page.locator('#next').click();await page.waitForFunction(next=>window.__YEARBOOK__.page===next&&window.__YEARBOOK__.state==='READING',next);}
  assert.equal(await page.locator('#reader,#reader-toggle,.chapter-rail').count(),0);
  pass('Built dist serves with production CSP, local fonts and interactive 3D');
  await page.evaluate(()=>window.__YEARBOOK__.close());
  await page.locator('#admin-link').click();
  await page.getByLabel('Username',{exact:true}).fill('production-qa');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Masuk dashboard'}).click();
  await page.getByRole('heading',{name:'Ringkasan',exact:true}).waitFor();
  await page.locator('[data-section="cover"]').first().click();
  await page.locator('[data-path="cover.tagline"]').fill('OUR PRODUCTION CHECK');
  await page.getByRole('button',{name:'Simpan perubahan',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-unsaved]')?.textContent==='Tersimpan di database');
  assert.equal((await(await fetch(`${url}/api/content`)).json()).cover.tagline,'OUR PRODUCTION CHECK');
  pass('Production login and CSRF-protected CMS write persist');
  await page.locator('[data-action="exit"]').last().click();
  await page.locator('#experience').waitFor({state:'visible'});
  await page.evaluate(()=>window.__YEARBOOK__.open());
  await page.locator('#stage canvas').dispatchEvent('webglcontextlost');
  await page.locator('#retry-3d').waitFor({state:'visible'});
  assert.equal(await page.locator('#reader,#reader-toggle').count(),0);
  pass('Context loss presents a 3D retry action without switching into an HTML reader');
  await page.close();
  const offline=await browser.newPage({viewport:{width:1440,height:960}});
  await offline.route('**/api/**',route=>route.abort());
  await offline.goto(url);await offline.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  await offline.locator('#loading').waitFor({state:'hidden'});
  assert.match(await offline.locator('#fallback-note').textContent(),/MODE OFFLINE/);
  await offline.evaluate(()=>window.__YEARBOOK__.open());
  for(const next of [4,6,8,10]){await offline.locator('#next').click();await offline.waitForFunction(next=>window.__YEARBOOK__.page===next&&window.__YEARBOOK__.state==='READING',next);}
  const composePoint=await offline.evaluate(()=>{const r=window.__YEARBOOK__.rig;const v=r.camera.position.clone().set(1.175,-1.116,.1);r.book.localToWorld(v);v.project(r.camera);const box=r.canvas.getBoundingClientRect();return{x:box.left+(v.x+1)*box.width/2,y:box.top+(1-v.y)*box.height/2};});
  await offline.mouse.click(composePoint.x,composePoint.y);
  await offline.locator('#letter-dialog').waitFor({state:'visible'});
  await offline.getByLabel('Surat ini untuk').selectOption('1');
  await offline.getByLabel('Yang ingin kamu sampaikan').fill('Pesan yang tidak boleh diklaim tersimpan saat offline.');
  await offline.getByRole('button',{name:'Kirim surat'}).click();
  await offline.getByText('Backend belum terhubung. Jalankan npm run dev untuk mengirim pesan.').waitFor();
  pass('API outage clearly labels offline seed content and refuses false message success');
  await offline.close();
  const noGL=await browser.newPage({viewport:{width:390,height:844}});
  await noGL.addInitScript(()=>{const native=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return /webgl/.test(type)?null:native.call(this,type,...args);};});
  await noGL.goto(url);await noGL.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  await noGL.locator('#retry-3d').waitFor({state:'visible'});assert.equal(await noGL.locator('#reader,#reader-toggle').count(),0);
  pass('A device without WebGL receives a clear 3D recovery state, never a hidden reader');await noGL.close();
  assert.deepEqual(errors,[]);pass('No JavaScript errors or CSP violations in production flow');
}catch(error){results.push({name:'Production integration',status:'FAIL',detail:error.stack});console.error(error);process.exitCode=1;}
finally{
  await writeFile('docs/qa/production-results.json',JSON.stringify({results,errors,limits:['Local HTTP production-mode build; external HTTPS reverse proxy not tested']},null,2));
  await browser.close();await new Promise(resolve=>server.close(resolve));app.locals.close();
  assert.equal(dirname(resolve(dataDir)),resolve(tmpdir()));assert.ok(dataDir.includes('yearbook-production-'));
  await rm(dataDir,{recursive:true,force:true});
}
